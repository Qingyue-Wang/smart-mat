static void oled_gpio_write(gpio_num_t pin, int level)
{
    gpio_set_level(pin, level);
}

static void oled_spi_write_byte(uint8_t value)
{
    for (int i = 0; i < 8; i++) {
        oled_gpio_write(OLED_SCK, 0);
        oled_gpio_write(OLED_MOSI, (value & 0x80) != 0);
        esp_rom_delay_us(1);
        oled_gpio_write(OLED_SCK, 1);
        esp_rom_delay_us(1);
        value <<= 1;
    }
}

static void oled_write_command(uint8_t command)
{
    oled_gpio_write(OLED_CS, 0);
    oled_gpio_write(OLED_DC, 0);
    oled_spi_write_byte(command);
    oled_gpio_write(OLED_CS, 1);
}

static void oled_write_data(const uint8_t *data, size_t len)
{
    oled_gpio_write(OLED_CS, 0);
    oled_gpio_write(OLED_DC, 1);
    for (size_t i = 0; i < len; i++) {
        oled_spi_write_byte(data[i]);
    }
    oled_gpio_write(OLED_CS, 1);
}

static void oled_set_pixel(int x, int y, bool on)
{
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) {
        return;
    }

    uint16_t index = x + (y / 8) * OLED_WIDTH;
    uint8_t mask = 1U << (y % 8);

    if (on) {
        s_buffer[index] |= mask;
    } else {
        s_buffer[index] &= (uint8_t)~mask;
    }
}

static void oled_clear(void)
{
    memset(s_buffer, 0, sizeof(s_buffer));
}

static void oled_draw_char(int x, int y, char c)
{
    if (c < 32 || c > 127) {
        c = '?';
    }

    const uint8_t *glyph = font5x7[(int)c - 32];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            oled_set_pixel(x + col, y + row, (bits >> row) & 0x01);
        }
    }
}

static void oled_draw_text(int x, int y, const char *text)
{
    while (*text != '\0') {
        oled_draw_char(x, y, *text++);
        x += 6;
    }
}

static void oled_draw_hline(int x, int y, int width, bool on)
{
    for (int i = 0; i < width; i++) {
        oled_set_pixel(x + i, y, on);
    }
}

static void oled_draw_vline(int x, int y, int height, bool on)
{
    for (int i = 0; i < height; i++) {
        oled_set_pixel(x, y + i, on);
    }
}

static void oled_draw_rect(int x, int y, int width, int height, bool on)
{
    oled_draw_hline(x, y, width, on);
    oled_draw_hline(x, y + height - 1, width, on);
    oled_draw_vline(x, y, height, on);
    oled_draw_vline(x + width - 1, y, height, on);
}

static void oled_fill_rect(int x, int y, int width, int height, bool on)
{
    for (int dy = 0; dy < height; dy++) {
        for (int dx = 0; dx < width; dx++) {
            oled_set_pixel(x + dx, y + dy, on);
        }
    }
}

static void oled_draw_progress_bar(int x, int y, int width, int height, float progress)
{
    if (progress < 0.0f) {
        progress = 0.0f;
    }
    if (progress > 1.0f) {
        progress = 1.0f;
    }

    oled_draw_rect(x, y, width, height, true);

    int fill_width = (int)((width - 2) * progress);
    oled_fill_rect(x + 1, y + 1, fill_width, height - 2, true);
}

static void oled_refresh(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        oled_write_command((uint8_t)(0xB0 + page));
        oled_write_command(0x00);
        oled_write_command(0x10);
        oled_write_data(&s_buffer[page * OLED_WIDTH], OLED_WIDTH);
    }
}

void display_init(void)
{
    gpio_config_t io_conf = {
        .pin_bit_mask = (1ULL << OLED_SCK) | (1ULL << OLED_MOSI) |
                        (1ULL << OLED_RES) | (1ULL << OLED_DC) | (1ULL << OLED_CS),
        .mode = GPIO_MODE_OUTPUT,
        .pull_up_en = GPIO_PULLUP_DISABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type = GPIO_INTR_DISABLE,
    };
    gpio_config(&io_conf);

    oled_gpio_write(OLED_CS, 1);
    oled_gpio_write(OLED_SCK, 0);
    oled_gpio_write(OLED_RES, 0);
    vTaskDelay(pdMS_TO_TICKS(20));
    oled_gpio_write(OLED_RES, 1);
    vTaskDelay(pdMS_TO_TICKS(20));

    oled_write_command(0xAE);
    oled_write_command(0xD5);
    oled_write_command(0x80);
    oled_write_command(0xA8);
    oled_write_command(0x3F);
    oled_write_command(0xD3);
    oled_write_command(0x00);
    oled_write_command(0x40);
    oled_write_command(0x8D);
    oled_write_command(0x14);
    oled_write_command(0x20);
    oled_write_command(0x00);
    oled_write_command(0xA1);
    oled_write_command(0xC8);
    oled_write_command(0xDA);
    oled_write_command(0x12);
    oled_write_command(0x81);
    oled_write_command(0xCF);
    oled_write_command(0xD9);
    oled_write_command(0xF1);
    oled_write_command(0xDB);
    oled_write_command(0x40);
    oled_write_command(0xA4);
    oled_write_command(0xA6);
    oled_write_command(0xAF);

    oled_clear();
    oled_refresh();
}

void display_show_boot(const char *line1, const char *line2)
{
    oled_clear();
    oled_draw_text(0, 8, line1);
    oled_draw_text(0, 24, line2);
    oled_refresh();
}

void display_show_status(const app_status_t *status)
{
    char line[32];
    float progress = 0.0f;

    if (status->target_ml > 0.0f) {
        progress = status->total_drink_g / status->target_ml;
    }

    oled_clear();

    oled_draw_text(0, 0, status->remind ? "DRINK WATER!" : "SMART COASTER");

    snprintf(line, sizeof(line), "Cup:%s W:%5.0fg", status->cup_present ? "ON" : "OFF", status->weight_g);
    oled_draw_text(0, 12, line);

    snprintf(line, sizeof(line), "Last:%5.0fg", status->last_drink_g);
    oled_draw_text(0, 24, line);

    snprintf(line, sizeof(line), "Tot:%4.0fg T:%4.0f", status->total_drink_g, status->target_ml);
    oled_draw_text(0, 36, line);

    oled_draw_progress_bar(0, 48, 128, 10, progress);

    snprintf(line, sizeof(line), "%3lu s", (unsigned long)status->next_reminder_s);
    oled_draw_text(92, 24, line);

    oled_refresh();
}
